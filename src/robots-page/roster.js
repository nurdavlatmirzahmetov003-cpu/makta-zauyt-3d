import { makeHumanoid, makeCleaner, makeSpider, makeRepairer } from './models.js';
import { PALETTE } from '../data.js';

const glow = (c) => new THREE.MeshStandardMaterial({ color: c, emissive: c, emissiveIntensity: 1.6 });

/* ---------- Adapters giving the factory builders the same rig interface ---------- */
function marzhan() {
  const g = makeMarzhan();
  g.userData.rig = {
    kind: 'flyer', lights: [], accents: [], hover: 1.15, light: false,
    update(dt, s) { g.userData.update(dt, { talking: s.talking, gesture: s.action === 'wave' || s.action === 'work' ? 1 : 0, light: this.light, speed: s.moving ? 6 : 0 }); },
  };
  return g;
}
function arm() {
  const box = new THREE.Mesh(new THREE.BoxGeometry(0.42, 0.3, 0.32), new THREE.MeshStandardMaterial({ color: '#c9a06a', roughness: 0.8 }));
  const a = new RobotArm({ scale: 1, poses: RobotArm.pickPlace(0, Math.PI / 2, 0.9), payload: box });
  const g = new THREE.Group();
  g.add(a);
  const status = new THREE.Mesh(new THREE.TorusGeometry(0.6, 0.03, 6, 32).rotateX(Math.PI / 2), glow(PALETTE.teal));
  status.position.y = 0.38;
  g.add(status);
  let t = 0;
  g.userData.rig = {
    kind: 'arm', lights: [status.material], accents: [status.material],
    update(dt, s) {
      t += dt;
      if (s.action === 'work') a.update(dt, 1);
      else if (s.action === 'wave') a.apply({ yaw: Math.sin(t * 3) * 0.4, sh: -0.2, el: 0.4, wr: Math.sin(t * 9) * 0.7, grip: 0, hold: 0 });
      else if (s.action === 'dance') a.apply({ yaw: Math.sin(t * 4) * 1.2, sh: 0.3 + Math.sin(t * 8) * 0.3, el: 0.9 + Math.sin(t * 6) * 0.5, wr: Math.sin(t * 12), grip: 0, hold: 0 });
      else a.apply({ yaw: Math.sin(t * 0.5) * 0.2, sh: 0.15, el: 0.85, wr: 0.6, grip: 0, hold: 0 });
    },
  };
  return g;
}
function amr() {
  const bale = new THREE.Mesh(new THREE.BoxGeometry(0.9, 0.62, 1.1).translate(0, 0.31, 0), new THREE.MeshStandardMaterial({ color: '#f4efe2', roughness: 0.95 }));
  const g = makeAMR({ load: bale });
  const strip = new THREE.Mesh(new THREE.BoxGeometry(1.04, 0.05, 1.64), glow(PALETTE.teal));
  strip.position.y = 0.2;
  g.add(strip);
  g.userData.rig = { kind: 'wheeled', lights: [strip.material], accents: [strip.material], update() {} };
  return g;
}
function forklift() {
  const g = makeForklift();
  const lamp = new THREE.Mesh(new THREE.SphereGeometry(0.1, 10, 8), glow('#ffb347'));
  lamp.position.set(0, 1.0, -0.6);
  g.add(lamp);
  let t = 0;
  g.userData.rig = {
    kind: 'wheeled', lights: [lamp.material], accents: [lamp.material],
    update(dt, s) { t += dt; g.userData.forks.position.y = s.action === 'work' ? 0.2 + (1 - Math.cos(t * 1.6)) * 0.8 : s.action === 'dance' ? 0.2 + Math.abs(Math.sin(t * 5)) * 0.5 : 0.2; },
  };
  return g;
}
function drone() {
  const g = makeDrone();
  const laser = new THREE.Mesh(new THREE.ConeGeometry(0.9, 2.2, 24, 1, true).translate(0, -1.1, 0),
    new THREE.MeshBasicMaterial({ color: '#ff4a3d', transparent: true, opacity: 0.25, blending: THREE.AdditiveBlending, depthWrite: false, side: THREE.DoubleSide }));
  laser.visible = false;
  g.add(laser);
  let t = 0;
  g.userData.rig = {
    kind: 'flyer', lights: [], accents: [], hover: 1.3,
    update(dt, s) {
      t += dt;
      for (const r of g.userData.rotors) r.rotation.y += dt * (s.sit ? 8 : 40);
      laser.visible = s.action === 'work';
      laser.rotation.z = Math.sin(t * 2) * 0.35;
    },
  };
  return g;
}
function harvester() {
  const g = buildHarvester();
  const { front, rear } = g.userData;
  g.userData.rig = {
    kind: 'wheeled', lights: [], accents: [],
    update(dt, s) { const v = s.moving || s.action === 'work' ? 3 : s.action === 'dance' ? 6 : 0; front.rotation.x += v * dt; rear.rotation.x += v * 1.4 * dt; },
  };
  return g;
}

